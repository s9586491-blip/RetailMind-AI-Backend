"""Pydantic schemas for capital allocation and portfolio expansion optimization.
"""

from typing import List, Optional
from pydantic import BaseModel, Field


class LocationCandidate(BaseModel):
    """Candidate store expansion opportunity under consideration."""

    id: str = Field(
        ...,
        description="Unique identifier for the location candidate",
        examples=["LOC-01"]
    )
    name: str = Field(
        ...,
        description="Location name or concept designation",
        examples=["Downtown Flagship Store"]
    )
    capex_required: float = Field(
        ...,
        ge=0,
        description="Initial capital expenditure (CapEx) required to build or lease the store in USD",
        examples=[350000.0]
    )
    expected_annual_revenue: float = Field(
        ...,
        ge=0,
        description="Estimated annual gross revenue in USD",
        examples=[1400000.0]
    )
    expected_annual_costs: float = Field(
        ...,
        ge=0,
        description="Estimated annual operating costs (OpEx) in USD",
        examples=[980000.0]
    )
    expected_roi_pct: float = Field(
        ...,
        description="Estimated initial return on investment percentage ((Annual Profit / CapEx) * 100)",
        examples=[120.0]
    )
    risk_level: str = Field(
        default="medium",
        description="Risk rating ('low', 'medium', 'high')",
        examples=["medium"]
    )
    store_format: Optional[str] = Field(
        default="Standard",
        description="Store format (e.g. Flagship, Boutique, Pop-Up, Mall)",
        examples=["Flagship"]
    )


class PortfolioRequest(BaseModel):
    """Input payload for optimizing capital allocation across candidate store locations."""

    total_budget: float = Field(
        ...,
        gt=0,
        description="Total available capital budget in USD for retail expansion",
        examples=[1000000.0]
    )
    risk_tolerance: str = Field(
        default="moderate",
        description="Portfolio risk appetite: 'conservative', 'moderate', or 'aggressive'",
        examples=["moderate"]
    )
    candidates: List[LocationCandidate] = Field(
        ...,
        min_length=1,
        description="List of candidate store locations competing for capital allocation"
    )
    max_locations: Optional[int] = Field(
        default=None,
        ge=1,
        description="Optional maximum number of store openings permitted in this tranche",
        examples=[3]
    )


class SelectedLocation(BaseModel):
    """Store location selected for capital deployment."""

    candidate_id: str = Field(..., description="ID of the selected candidate")
    name: str = Field(..., description="Name of the selected store location")
    allocated_capex: float = Field(..., description="CapEx allocated to this location in USD")
    expected_annual_revenue: float = Field(..., description="Estimated annual revenue in USD")
    expected_annual_profit: float = Field(..., description="Estimated annual net profit in USD")
    expected_roi_pct: float = Field(..., description="Projected ROI percentage")
    risk_level: str = Field(..., description="Assessed risk tier")
    selection_rationale: str = Field(..., description="Specific justification for greenlighting this investment")


class PortfolioResponse(BaseModel):
    """Optimal capital allocation and strategic portfolio recommendations."""

    total_budget: float = Field(..., description="Total capital budget provided in USD")
    allocated_budget: float = Field(..., description="Total capital successfully allocated in USD")
    remaining_budget: float = Field(..., description="Unallocated reserve capital in USD")
    selected_locations: List[SelectedLocation] = Field(..., description="List of funded store locations")
    deferred_locations: List[str] = Field(
        default_factory=list,
        description="IDs of candidate locations deferred or not funded"
    )
    portfolio_roi_pct: float = Field(
        ...,
        description="Aggregate expected ROI across all funded locations"
    )
    total_projected_annual_profit: float = Field(
        ...,
        description="Total expected annual net profit generated by funded locations in USD"
    )
    portfolio_risk_rating: str = Field(
        ...,
        description="Aggregate risk rating of the recommended portfolio (Conservative, Balanced, High-Growth)"
    )
    strategic_rationale: str = Field(
        ...,
        description="Strategic analysis explaining why this allocation maximizes retail footprint and return"
    )
